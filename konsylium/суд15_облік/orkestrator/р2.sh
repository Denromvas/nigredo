#!/bin/sh
# р2.sh МІТКА ПРОГРАМА [прапорці] [-- аргументи програми]
# Один запуск кожного виконавця з власним слідом: норма 1.1 (ngr), 1.2 Атанор (../ngr15.sh), 1.2 еталон (../нгр15_еталон.sh).
# Друкує кроки (поле «кроків» кінця сліду) або текст зупинки, час і найбільшу памʼять (GNU time). Сліди — р2сліди/.
# ПРОПУСТИТИ=11 — без норми 1.1; ЛИШЕ_А=1 — лише Атанор.
М="$1"; shift
П="$1"; shift
mkdir -p р2сліди р2звіти
Р="р2звіти/$М.txt"
: > "$Р"
одне() {
  мітка="$1"; shift
  кмд="$1"; shift
  с="р2сліди/${М}_$мітка.jsonl"
  rm -f "$с" "$с.дані"
  /usr/bin/time -f "%e с %M КБ" -o "р2сліди/${М}_$мітка.час" "$кмд" "$П" --слід "$с" "$@" > "р2сліди/${М}_$мітка.out" 2> "р2сліди/${М}_$мітка.err"
  код=$?
  кр=$(tail -n 1 "$с" | grep -o '"кроків": [0-9]*' | grep -o '[0-9]*$')
  зуп=$(tail -n 1 "$с" | grep -o '"повідомлення": "[^"]*"' | head -c 160)
  printf '%-8s код %s, кроків %s %s, %s\n' "$мітка" "$код" "${кр:--}" "$зуп" "$(tail -n 1 "р2сліди/${М}_$мітка.час")" >> "$Р"
}
[ "$ПРОПУСТИТИ" = 11 ] || [ -n "$ЛИШЕ_А" ] || одне 1.1 ngr "$@"
одне А ../ngr15.sh "$@"
[ -n "$ЛИШЕ_А" ] || одне Е ../нгр15_еталон.sh "$@"
cat "$Р"
