#!/bin/sh
# ./к.sh ПРОГРАМА.ngr [прапорці] [-- аргументи]: останній запис сліду (кроки, зупинка) — норма 1.1, Атанор 1.2, еталон 1.2
P="$1"; shift
for W in ngr ../ngr15.sh ../нгр15_еталон.sh; do
  printf '%s: ' "$W"
  "$W" "$P" --слід - "$@" 2>&1 >/dev/null | grep -a -E '"кроків"|^✗|помилка' | tail -n 2 | sed -E 's/"попередній".*//' | tr '\n' ' '
  echo
done
