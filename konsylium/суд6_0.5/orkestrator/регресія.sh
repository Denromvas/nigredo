#!/bin/bash
# Регресія: мої атаки минулих судів (суд 5, повторний огляд 0.4.3) — на 0.5. Запуск з теки orkestrator.
cd "$(dirname "$0")" || exit 1
for f in атаки_минулих_судів/*.ngr; do
  cp "$f" "./$(basename "$f")"
done
run() {   # run ФАЙЛ [аргументи ngr…]
  echo "=== $*"
  timeout 30 ngr "$@" 2>&1 | head -c 700
  echo " [код ${PIPESTATUS[0]}]"
}
for f in атака6_*.ngr р2_1_*.ngr р2_2_*.ngr р2_4_*.ngr р2_5_*.ngr р2_6_*.ngr р2_7_*.ngr р2_9_*.ngr; do
  run "$f"
done
echo "=== згенеровані"
run звіти/6_7_розкладене.ngr
run звіти/6_8_crlf.ngr
run звіти/р2_7_cr.ngr
echo "=== печатки"
run --печатка атака6_6_печатка_без_керівних.ngr
run --печатка атака6_6б_печатка_коротка.ngr
run --печатка р2_5_печатка_шлях.ngr
echo "=== сурогат в аргументах (р2_argv)"
run р2_argv.ngr -- $'\xff\xfe'
echo "=== слід 6.9 з програмою"
rm -f сліди_мої/р_6_9.jsonl
timeout 30 ngr --слід сліди_мої/р_6_9.jsonl атака6_9_слід_роздільник.ngr > /dev/null 2>&1
run --перевірити-слід сліди_мої/р_6_9.jsonl атака6_9_слід_роздільник.ngr
echo "=== слід 6.8 crlf з програмою"
rm -f сліди_мої/р_6_8.jsonl
timeout 30 ngr --слід сліди_мої/р_6_8.jsonl звіти/6_8_crlf.ngr > /dev/null 2>&1
run --перевірити-слід сліди_мої/р_6_8.jsonl звіти/6_8_crlf.ngr
echo "=== слід р2.2 (хвіст виводу)"
rm -f сліди_мої/р_2_2.jsonl
timeout 30 ngr --слід сліди_мої/р_2_2.jsonl р2_2_хвіст_виводу.ngr > /dev/null 2>&1
grep -c 'ДЛЯ ОТРИМУВАЧА' сліди_мої/р_2_2.jsonl
echo "=== слід р2.6 (агент субагента)"
rm -f сліди_мої/р_2_6.jsonl
timeout 30 ngr --слід сліди_мої/р_2_6.jsonl р2_6_субагент_слеш.ngr > /dev/null 2>&1
grep -o '"агент": "[^"]*"' сліди_мої/р_2_6.jsonl | sort -u
