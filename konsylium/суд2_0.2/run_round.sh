#!/usr/bin/env bash
# ./run_round.sh 1|2 — запустити раунд для всіх учасників-Claude паралельно
R=$1; K=$(cd "$(dirname "$0")" && pwd)
for m in skeptyk praktyk movoznavets audytor novachok; do
  if [ "$R" = 1 ]; then
    P="Ти учасник консиліуму. Твоя роль — у CLAUDE.md цієї теки. Прочитай ../ПРАВИЛА.md і ../ЗАВДАННЯ.md та виконай РАУНД 1 повністю: розвʼяжи завдання А, Б, В, Г у файлах своєї теки, запускаючи ngr, і збережи звіт у звіт_раунд1.md за шаблоном. Працюй самостійно, нічого не питай."
  else
    P="Ти учасник консиліуму. Твоя роль — у CLAUDE.md цієї теки. Це РАУНД 2 (обговорення). Звіти першого раунду всіх учасників зібрано в ../protokol/раунд1/ — прочитай їх (тепер можна), а також свій звіт_раунд1.md. Збережи звіт_раунд2.md за правилами раунду 2 з ../ПРАВИЛА.md. Нічого не питай."
  fi
  ( cd "$K/$m" && claude -p "$P" --allowedTools "Read,Write,Edit,Glob,Grep,Bash(ngr:*)" > "$K/protokol/лог_${m}_р$R.txt" 2>&1; echo "$m exit $?" ) &
done
wait
