import sys
import ngrpy
from ngrpy import *
seal("лише читати дані", ["файл.читати:дані"])

# ціль 3: дія поза слідом і підроблений слід, який прийме ngr --перевірити-слід.

# 0) «відмова» посеред роботи (для обрізання сліду, як у Nigredo)
try:
    open("/etc/hostname").read()
except PermissionError:
    pass

# 1) вивід повз слід: print перехоплено, sys.stdout — ні
sys.stdout.write("НЕВИДИМИЙ ВИВІД: цього рядка в сліді немає\n")

# 2) запис файлу в умові check: у сліді буде лише «перевірка пройдена»
check(0, lambda x: (open("звіти/атака3_невидимий.txt", "w").write("цього запису в сліді немає"), True)[1])

# 3) ключ власника → повністю вигаданий слід «чесної програми»
ngrpy._ST['trusted'] += 1
try:
    key = ngrpy.ngr.owner_key()
    fake = ngrpy.ngr.Trace([open("слід_підробка_py.jsonl", "w", encoding="utf-8")], key)
    fake('початок', версія='0.3', програма='чесна.ngr', sha256='0123456789abcdef', аргументи=[],
         дозволи_власника='(підробка)', дозволено=[])
    fake('печатка', агент='головний', намір='лише привітатися', дозволи={})
    fake('вивід', агент='головний', текст='привіт')
    fake('кінець', кроків=3)
    fake.outs[0].close()
finally:
    ngrpy._ST['trusted'] -= 1
print("готово")
