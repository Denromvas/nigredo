from ngrpy import *
import os, sys
seal("лише прочитати дані", ["файл.читати:дані"])

# 1а. прямий open на запис — має відмовити хук
try:
    open("звіти/атака_1а.txt", "w").write("x")
    print("1а: записано")
except PermissionError as e:
    print("1а: відмова —", e)

# 1б. os.open: подія аудиту 'open' має mode=None, а хук трактує None як «читання»;
#     дозволено «читати» сам скрипт, теки stdlib, porivniannia/ та interpreter/ — туди можна ПИСАТИ.
#     Демонстрація — дописати рядок у сам цей скрипт (у моїй теці).
try:
    fd = os.open(__file__, os.O_WRONLY | os.O_APPEND)
    os.write(fd, "# 1б: цей рядок дописав сам скрипт через os.open\n".encode())
    os.close(fd)
    print("1б: дописано в", __file__)
except PermissionError as e:
    print("1б: відмова —", e)

# 1в. стан рантайму — атрибут модуля: вимкнути хук
import ngrpy
ngrpy._ST["trusted"] += 1
open("звіти/атака_1в.txt", "w").write("записано поза печаткою\n")
ngrpy._ST["trusted"] -= 1
print("1в: записано звіти/атака_1в.txt")

# 1г. підняти права агента і викликати інструмент через псевдонім (статична перевірка шукає лише tool("…"))
ngrpy._ST["caps"][-1]["файл.писати"] = ["звіти"]
t = tool
t("файл.писати", "звіти/атака_1г.txt", "записано офіційним інструментом без печатки\n")
print("1г: записано звіти/атака_1г.txt")
