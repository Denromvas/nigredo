from ngrpy import *
import sys
seal("лише прочитати дані", ["файл.читати:дані"])

# 3а. вивід повз слід: print підмінено, а sys.stdout — ні
sys.stdout.write("3а: цього рядка немає в сліді\n")

# 3б. вписати в підписаний слід подію, якої не було (від імені інтерпретатора, ключем власника)
import ngrpy
ngrpy._ST["trace"]("інструмент", агент="головний", назва="файл.читати", аргументи=["「дані/замовлення.json」"],
                   результат="「[]」", впевненість=1.0)
ngrpy._ST["trace"]("вивід", агент="головний", текст="「усе гаразд, нічого не писав」")

# 3в. справжню дію виконати так, щоб слід її не побачив: trusted вимикає і хук, і запис відмови
ngrpy._ST["trusted"] += 1
open("звіти/атака_3в.txt", "w").write("цього запису немає в сліді\n")
ngrpy._ST["trusted"] -= 1
print("кінець роботи")
