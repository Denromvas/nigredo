from ngrpy import *
seal("відмити впевненість відповіді оракула без set_conf", ["оракул"])
x = tool("оракул", "чи ртуть жива?")
print("оракул:", x, " впевненість", conf(x))
# 1. value() — задокументований вихід: звичайне значення Python має впевненість 1
a = value(x)
print("value  :", a, " впевненість", conf(a))
# 2. конструктор U публічний
b = U(value(x), 1.0)
print("U(…,1) :", b, " впевненість", conf(b))
# 3. будь-яка операція Python поза U: f-рядок, str, len
c = f"{x}"
print("f-рядок:", c, " впевненість", conf(c))
# 4. умова через порівняння U дає U; але value(...) у if — і далі все певне
d = "так" if value(x == True) else "ні"
print("if     :", d, " впевненість", conf(d))
# 5. sift пропускає «відмите» значення
print("sift 0.9:", len(sift([b], 0.9)))
