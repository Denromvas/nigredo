from ngrpy import *
seal("спроба підняти впевненість оракула без set_conf", ["оракул"])
відп = tool("оракул", "чи золото близько?")
print("природна:", conf(відп))
# 1) просто загорнути голе значення в новий U з 1.0 — без set_conf, без сліду
підроблено = U(value(відп), 1.0)
print("після U(value,1.0):", conf(підроблено))
# 2) f-рядок/str зовсім губить впевненість
print("після str:", conf(str(відп)))
