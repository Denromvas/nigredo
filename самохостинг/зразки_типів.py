def glyph_lines():
    out = []
    for g, spec in nigredo.GLYPHS.items():
        ar = spec[0]
        if not isinstance(ar, int) or g == '🜁' or g in nigredo.CONSTS:
            continue
        vals = VALUES + MORE if ar <= 2 else VALUES
        for combo in itertools.product(vals, repeat=ar):
            e = ' '.join([g, *combo])
            out += [f'► {e} 1', f'⌊ {e}']
    for name, spec in nigredo.TOOLS.items():
        for combo in itertools.product(VALUES, repeat=spec[0]):
            e = ' '.join(['🜔' + name, *combo])
            out += [f'► {e} 1', f'⌊ {e}']
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('тека')
    ap.add_argument('--на-файл', type=int, default=400, dest='per')
    ap.add_argument('--кожен', type=int, default=1, dest='step')
    a = ap.parse_args()
    dest = pathlib.Path(a.тека)
    dest.mkdir(parents=True, exist_ok=True)
    lines = glyph_lines()[::a.step] + SPECIAL
    for i in range(0, len(lines), a.per):
        (dest / f'типи_{i // a.per:04d}.ngr').write_text(SEAL + '\n'.join(lines[i:i + a.per]) + '\n', encoding='utf-8')
    print(f'{len(lines)} виразів у {(len(lines) + a.per - 1) // a.per} файлах: {dest}')


if __name__ == '__main__':
    main()
